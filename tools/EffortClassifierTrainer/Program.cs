// Trains Auto effort's head: multinomial logistic regression (L2, class-balanced, full-batch
// gradient descent) over frozen all-MiniLM-L6-v2 embeddings.
//
//   dotnet run --project tools/EffortClassifierTrainer -- \
//     tools/EffortClassifierTrainer/effort-dataset.tsv src/ClaudeCode.Core.ViewModels/Effort/Model
//
// Prints 5-fold cross-validated accuracy (raw argmax and after AutoEffortPolicy), then trains on
// every row and writes <model dir>/effort-head.txt. Deterministic: no random state.
using ClaudeCode.Core.Effort;
using System;
using System.Globalization;
using System.IO;
using System.Linq;

if (args.Length != 2)
{
    Console.Error.WriteLine("usage: EffortClassifierTrainer <dataset.tsv> <model directory>");
    return 2;
}

const int Classes = 3;
const int Epochs = 3000;
const double LearningRate = 2.0;
const double L2 = 1e-3;

var rows = File.ReadLines(args[0])
    .Where(line => line.Length > 0 && line[0] != '#')
    .Select(line => line.Split('\t', 2))
    .Select(parts => (Label: (int)Enum.Parse<EffortLevel>(parts[0], ignoreCase: true), Text: parts[1]))
    .ToArray();

using var encoder = MiniLmEncoder.Load(args[1]);
var x = rows.Select(row => encoder.Embed(row.Text)).ToArray();
var y = rows.Select(row => row.Label).ToArray();
Console.WriteLine($"{rows.Length} rows: " + string.Join(", ", Enumerable.Range(0, Classes).Select(c => $"{(EffortLevel)c}={y.Count(label => label == c)}")));

int rawHits = 0, policyHits = 0, underEffort = 0;
for (int fold = 0; fold < 5; fold++)
{
    var train = Enumerable.Range(0, rows.Length).Where(i => i % 5 != fold).ToArray();
    var model = Train(train);
    foreach (var i in Enumerable.Range(0, rows.Length).Where(i => i % 5 == fold))
    {
        var p = Probabilities(model, x[i]);
        rawHits += Array.IndexOf(p, p.Max()) == y[i] ? 1 : 0;
        var decided = (int)AutoEffortPolicy.Decide(p.Select(value => (float)value).ToArray());
        policyHits += decided == y[i] ? 1 : 0;
        underEffort += decided < y[i] ? 1 : 0;
    }
}
Console.WriteLine($"5-fold CV: argmax {rawHits * 100.0 / rows.Length:F1}%, policy {policyHits * 100.0 / rows.Length:F1}%, policy under-effort {underEffort * 100.0 / rows.Length:F1}%");

var final = Train(Enumerable.Range(0, rows.Length).ToArray());
var output = Path.Combine(args[1], EffortHead.FileName);
using (var writer = new StreamWriter(output) { NewLine = "\n" })
{
    writer.WriteLine("# Auto effort head for all-MiniLM-L6-v2: per class (Low, Medium, High) bias then 384 weights.");
    writer.WriteLine("# Generated by tools/EffortClassifierTrainer from effort-dataset.tsv; do not edit by hand.");
    foreach (var row in final)
        writer.WriteLine(string.Join(" ", row.Select(value => ((float)value).ToString("R", CultureInfo.InvariantCulture))));
}
Console.WriteLine($"wrote {output}");
return 0;

// model[c] = [bias, w0..w383]
double[][] Train(int[] indices)
{
    int dims = MiniLmEncoder.Dimensions;
    var model = Enumerable.Range(0, Classes).Select(_ => new double[dims + 1]).ToArray();
    var counts = Enumerable.Range(0, Classes).Select(c => indices.Count(i => y[i] == c)).ToArray();
    var classWeight = counts.Select(count => indices.Length / (double)(Classes * Math.Max(count, 1))).ToArray();
    for (int epoch = 0; epoch < Epochs; epoch++)
    {
        var gradient = Enumerable.Range(0, Classes).Select(_ => new double[dims + 1]).ToArray();
        foreach (var i in indices)
        {
            var p = Probabilities(model, x[i]);
            for (int c = 0; c < Classes; c++)
            {
                double error = classWeight[y[i]] * (p[c] - (y[i] == c ? 1 : 0));
                gradient[c][0] += error;
                for (int d = 0; d < dims; d++) gradient[c][d + 1] += error * x[i][d];
            }
        }
        for (int c = 0; c < Classes; c++)
        {
            model[c][0] -= LearningRate * gradient[c][0] / indices.Length;
            for (int d = 1; d <= dims; d++)
                model[c][d] -= LearningRate * (gradient[c][d] / indices.Length + L2 * model[c][d]);
        }
    }
    return model;
}

static double[] Probabilities(double[][] model, float[] embedding)
{
    var logits = model.Select(row =>
    {
        double sum = row[0];
        for (int d = 0; d < embedding.Length; d++) sum += row[d + 1] * embedding[d];
        return sum;
    }).ToArray();
    double max = logits.Max();
    var exp = logits.Select(logit => Math.Exp(logit - max)).ToArray();
    double total = exp.Sum();
    return exp.Select(value => value / total).ToArray();
}
